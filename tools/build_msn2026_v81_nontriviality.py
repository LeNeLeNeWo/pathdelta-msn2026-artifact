def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build(output_root: Path = DATA_ROOT) -> Dict[str, Any]:
    if output_root.exists():
        shutil.rmtree(output_root)
    output_root.mkdir(parents=True)
    files = []
    for scenario in cases():
        root = output_root / "scenarios" / scenario["scenario_id"]
        (root / "baseline").mkdir(parents=True)
        (root / "baseline" / f"{scenario['device']}.conf").write_text(scenario["baseline"], encoding="utf-8")
        (root / "intent.json").write_text(json.dumps(scenario["intent"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
        (root / "visible_pre_observations.json").write_text(json.dumps(scenario["visible"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
        (root / "heldout_pre_observations.json").write_text(json.dumps(scenario["heldout"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
        (root / "scenario.json").write_text(
            json.dumps(
                {
                    "scenario_id": scenario["scenario_id"],
                    "freeze_version": "v81-nontriviality-1.0.0",
                    "visible_to_methods": ["baseline/", "intent.json", "visible_pre_observations.json"],
                    "oracle_only": ["heldout_pre_observations.json", "candidates/*/heldout_post_observations.json"],
                    "construction": "predeclared mechanism challenge; no envelope output used in candidate construction",
                },
                indent=2,
                sort_keys=True,
            ) + "\n",
            encoding="utf-8",
        )
        for candidate in scenario["candidates"]:
            candidate_root = root / "candidates" / candidate["candidate_id"]
            (candidate_root / "configs").mkdir(parents=True)
            (candidate_root / "configs" / f"{scenario['device']}.conf").write_text(candidate["config"], encoding="utf-8")
            (candidate_root / "visible_post_observations.json").write_text(json.dumps(candidate["visible"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
            (candidate_root / "heldout_post_observations.json").write_text(json.dumps(candidate["heldout"], indent=2, sort_keys=True) + "\n", encoding="utf-8")
            (candidate_root / "candidate.json").write_text(
                json.dumps(
                    {
                        "candidate_id": candidate["candidate_id"],
                        "mutation_origin": candidate["mutation_origin"],
                        "generated_without_envelope": True,
                        "expected_verdict_hidden_from_methods": True,
                    },
                    indent=2,
                    sort_keys=True,
                ) + "\n",
                encoding="utf-8",
            )
    for path in sorted(output_root.rglob("*")):
        if path.is_file():
            files.append({"path": path.relative_to(output_root).as_posix(), "sha256": sha256(path), "bytes": path.stat().st_size})
    manifest = {
        "dataset_id": "msn2026_v81_nontriviality",
        "version": "1.0.0",
        "seed": 8102026,
        "source": "fresh predeclared synthetic brownfield mechanism challenges",
        "license": "project-generated research artifact",
        "scenario_count": len(cases()),
        "candidate_count": sum(len(item["candidates"]) for item in cases()),
        "files": files,
    }
    (output_root / "dataset_manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


if __name__ == "__main__":
    print(json.dumps(build(), indent=2, sort_keys=True))
