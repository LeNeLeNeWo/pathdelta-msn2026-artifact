ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = ROOT / "data/msn2026_v81_nontriviality"


def record(device: str, neighbor: str, prefix: str, decision: str, local_pref: int | None) -> Dict[str, Any]:
    return {
        "behavior_id": f"{device}|{neighbor}|{prefix}",
        "device": device,
        "subject": neighbor,
        "fec": prefix,
        "attributes": {"decision": decision, "local_pref": local_pref, "session": "established"},
        "source": "independent_declared_scenario_oracle_v1",
    }


def with_attributes(rows: Iterable[Mapping[str, Any]], changes: Mapping[str, Mapping[str, Any]]) -> list[Dict[str, Any]]:
    output = []
    for original in rows:
        row = json.loads(json.dumps(original))
        row["attributes"].update(changes.get(row["behavior_id"], {}))
        row["source"] = "independent_declared_scenario_oracle_v1_post"
        output.append(row)
    return output


