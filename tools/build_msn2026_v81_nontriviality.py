#!/usr/bin/env python3
"""Build a frozen, mechanism-discriminating Change Envelope challenge set.

The cases are specified before evaluation.  Visible observations are available
to all methods; held-out observations are used only by the independent safety
oracle.  Configuration candidates are concrete mutations, not generated by the
envelope implementation.
"""

from __future__ import annotations

